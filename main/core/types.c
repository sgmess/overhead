static int cmp(const void *key, const void *elem)
{
    return strcmp(key, ((const type_name_t *)elem)->code);
}

const char *type_name(const char *code)
{
    const type_name_t *t = bsearch(code, TYPES, sizeof(TYPES) / sizeof(TYPES[0]), sizeof(TYPES[0]), cmp);
    return t ? t->name : NULL;
}
